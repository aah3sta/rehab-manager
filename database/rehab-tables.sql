CREATE DATABASE REHAB_DB;
USE REHAB_DB;

CREATE TABLE PATIENT(
    PATIENT_ID bigint PRIMARY KEY auto_increment,
    FULL_NAME VARCHAR(80) NOT NULL,
    GENDER ENUM('MALE', 'FEMALE', 'OTHER'),
    DATE_OF_BIRTH date NOT NULL,
    CONTACT VARCHAR(15) NOT NULL UNIQUE,
    REGISTRATION_DATE datetime DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE STAFF(
    STAFF_ID bigint PRIMARY KEY auto_increment,
    FULL_NAME VARCHAR(50) NOT NULL,
    CONTACT VARCHAR(15) NOT NULL,
    ROLE VARCHAR(50) NOT NULL
);


CREATE TABLE MEDICAL_ASSESSMENT(
    ASSESSMENT_ID BIGINT PRIMARY KEY auto_increment,
    PATIENT_ID BIGINT NOT NULL,
    STAFF_ID BIGINT NOT NULL,
    ASSESSMENT_DATE DATETIME NOT NULL DEFAULT current_timestamp,
    MEDICAL_HISTORY TEXT,
    ASSESSMENT_NOTES TEXT NOT NULL,
    DIAGNOSIS TEXT NOT NULL,

    FOREIGN KEY(PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    FOREIGN KEY(STAFF_ID) REFERENCES STAFF(STAFF_ID)
);

CREATE TABLE LAB_TESTS(
    LAB_TEST_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    ASSESSMENT_ID BIGINT NOT NULL,
    TEST_NAME VARCHAR(50) NOT NULL,
    TEST_DATE DATETIME NOT NULL,
    RESULTS TEXT NOT NULL,
    NOTES TEXT,

    FOREIGN KEY(ASSESSMENT_ID) REFERENCES MEDICAL_ASSESSMENT(ASSESSMENT_ID)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);


CREATE TABLE VITALS(
    VITAL_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PATIENT_ID BIGINT NOT NULL,
    STAFF_ID BIGINT NOT NULL,
    RECORD_DATE DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TEMPERATURE_CELSIUS DECIMAL(4,2) NOT NULL,
    PULSE_RATE INT NOT NULL,
    RESPIRATORY_RATE INT NOT NULL,
    GLUCOSE_LEVEL_MMOL_L DECIMAL(3,1) NOT NULL,
    SYSTOLIC_MMHG INT NOT NULL,
    DIASTOLIC_MMHG INT NOT NULL,

    FOREIGN KEY(PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
    ON DELETE CASCADE
    ON UPDATE CASCADE,

    FOREIGN KEY(STAFF_ID) REFERENCES STAFF(STAFF_ID)
);

CREATE TABLE THERAPY_SESSION(
    SESSION_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PATIENT_ID BIGINT NOT NULL,
    STAFF_ID BIGINT NOT NULL,
    SESSION_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DURATION_MINUTES INT NOT NULL,
    CHECK(DURATION_MINUTES > 0),
    THERAPY_NOTES TEXT NOT NULL,

    FOREIGN KEY(PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
    ON DELETE CASCADE 
    ON UPDATE CASCADE,

    FOREIGN KEY(STAFF_ID) REFERENCES STAFF(STAFF_ID)
);


CREATE TABLE MEDICATION_RECORD(
    RECORD_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PATIENT_ID BIGINT NOT NULL,
    STAFF_ID BIGINT NOT NULL,
    MEDICATION_NAME VARCHAR(200) NOT NULL,
    DOSAGE VARCHAR(70) NOT NULL,
    FREQUENCY VARCHAR(50) NOT NULL,
    START_DATE DATE NOT NULL DEFAULT (CURDATE()),
    INSTRUCTIONS TEXT NOT NULL,
    RECORD_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY(PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
    ON DELETE CASCADE 
    ON UPDATE CASCADE,

    FOREIGN KEY(STAFF_ID) REFERENCES STAFF(STAFF_ID)
);


CREATE TABLE DISCHARGE_AFTERCARE_PLAN(
    PLAN_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PATIENT_ID BIGINT NOT NULL,
    STAFF_ID BIGINT NOT NULL,
    DISCHARGE_DATE DATE NOT NULL,
    RECOVERY_GOALS TEXT NOT NULL,
    AFTERCARE_INSTRUCTIONS TEXT NOT NULL,
    EMERGENCY_RELAPSE_CONTACT VARCHAR(15),
    FOLLOW_UP_DATE DATE,

    FOREIGN KEY(PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
    ON DELETE CASCADE
    ON UPDATE CASCADE, 
    FOREIGN KEY(STAFF_ID) REFERENCES STAFF(STAFF_ID)
);
