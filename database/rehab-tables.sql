-- Rehabilitation Center Management System
-- Schema for all 8 modules
-- Run in MySQL 8+:  mysql -u root -p < sql/schema.sql

CREATE DATABASE IF NOT EXISTS REHAB_DB;
USE REHAB_DB;

CREATE TABLE IF NOT EXISTS PATIENT (
    PATIENT_ID        BIGINT       AUTO_INCREMENT PRIMARY KEY,
    FULL_NAME         VARCHAR(100) NOT NULL,
    GENDER            VARCHAR(10)  NOT NULL,
    DATE_OF_BIRTH     DATE         NOT NULL,
    CONTACT           VARCHAR(20)  NOT NULL,
    REGISTRATION_DATE TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_PATIENT_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER'))
);

CREATE TABLE IF NOT EXISTS STAFF (
    STAFF_ID   BIGINT       AUTO_INCREMENT PRIMARY KEY,
    FULL_NAME  VARCHAR(100) NOT NULL,
    CONTACT    VARCHAR(20)  NOT NULL,
    ROLE       VARCHAR(50)  NOT NULL
);

-- ON DELETE RESTRICT is what makes "delete when permitted" work:
-- a patient or staff member who has assessments cannot be deleted.
CREATE TABLE IF NOT EXISTS MEDICAL_ASSESSMENT (
    ASSESSMENT_ID    BIGINT       AUTO_INCREMENT PRIMARY KEY,
    PATIENT_ID       BIGINT       NOT NULL,
    STAFF_ID         BIGINT       NOT NULL,
    ASSESSMENT_DATE  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MEDICAL_HISTORY  TEXT,
    ASSESSMENT_NOTES TEXT         NOT NULL,
    DIAGNOSIS        VARCHAR(255) NOT NULL,
    CONSTRAINT FK_ASSESS_PATIENT FOREIGN KEY (PATIENT_ID)
        REFERENCES PATIENT (PATIENT_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_ASSESS_STAFF FOREIGN KEY (STAFF_ID)
        REFERENCES STAFF (STAFF_ID) ON DELETE RESTRICT,
    INDEX IDX_ASSESS_DATE (ASSESSMENT_DATE)
);

-- ===== Module 4: Laboratory tests (linked to an assessment) =====
CREATE TABLE IF NOT EXISTS LAB_TESTS (
    TEST_ID        BIGINT       AUTO_INCREMENT PRIMARY KEY,
    ASSESSMENT_ID  BIGINT       NOT NULL,
    TEST_NAME      VARCHAR(100) NOT NULL,
    TEST_DATE      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESULT         VARCHAR(255),              -- NULL while the test is pending
    NOTES          TEXT,
    CONSTRAINT FK_LAB_ASSESSMENT FOREIGN KEY (ASSESSMENT_ID)
        REFERENCES MEDICAL_ASSESSMENT (ASSESSMENT_ID) ON DELETE RESTRICT
);

-- ===== Module 5: Vitals =====
CREATE TABLE IF NOT EXISTS VITALS (
    VITALS_ID        BIGINT       AUTO_INCREMENT PRIMARY KEY,
    PATIENT_ID       BIGINT       NOT NULL,
    STAFF_ID         BIGINT       NOT NULL,
    RECORDED_AT      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TEMPERATURE      DECIMAL(4,1) NOT NULL,   -- degrees Celsius
    PULSE            INT          NOT NULL,   -- beats per minute
    BREATHING_RATE   INT          NOT NULL,   -- breaths per minute
    GLUCOSE          DECIMAL(4,1) NOT NULL,   -- mmol/L
    SYSTOLIC_BP      INT          NOT NULL,   -- mmHg
    DIASTOLIC_BP     INT          NOT NULL,   -- mmHg
    CONSTRAINT FK_VITALS_PATIENT FOREIGN KEY (PATIENT_ID)
        REFERENCES PATIENT (PATIENT_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_VITALS_STAFF FOREIGN KEY (STAFF_ID)
        REFERENCES STAFF (STAFF_ID) ON DELETE RESTRICT,
    INDEX IDX_VITALS_DATE (RECORDED_AT)
);

-- ===== Module 6: Therapy sessions =====
CREATE TABLE IF NOT EXISTS THERAPY_SESSION (
    SESSION_ID        BIGINT   AUTO_INCREMENT PRIMARY KEY,
    PATIENT_ID        BIGINT   NOT NULL,
    STAFF_ID          BIGINT   NOT NULL,
    SESSION_DATE      DATETIME NOT NULL,
    DURATION_MINUTES  INT      NOT NULL,
    NOTES             TEXT     NOT NULL,
    CONSTRAINT FK_THERAPY_PATIENT FOREIGN KEY (PATIENT_ID)
        REFERENCES PATIENT (PATIENT_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_THERAPY_STAFF FOREIGN KEY (STAFF_ID)
        REFERENCES STAFF (STAFF_ID) ON DELETE RESTRICT,
    CONSTRAINT CHK_THERAPY_DURATION CHECK (DURATION_MINUTES BETWEEN 5 AND 480),
    INDEX IDX_THERAPY_DATE (SESSION_DATE)
);

-- ===== Module 7: Medication records =====
CREATE TABLE IF NOT EXISTS MEDICATION_RECORD (
    RECORD_ID        BIGINT       AUTO_INCREMENT PRIMARY KEY,
    PATIENT_ID       BIGINT       NOT NULL,
    STAFF_ID         BIGINT       NOT NULL,   -- responsible staff member
    MEDICATION_NAME  VARCHAR(100) NOT NULL,
    DOSAGE           VARCHAR(50)  NOT NULL,   -- e.g. "500 mg"
    FREQUENCY        VARCHAR(50)  NOT NULL,   -- e.g. "Twice daily"
    INSTRUCTIONS     TEXT,
    RECORDED_DATE    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_MED_PATIENT FOREIGN KEY (PATIENT_ID)
        REFERENCES PATIENT (PATIENT_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_MED_STAFF FOREIGN KEY (STAFF_ID)
        REFERENCES STAFF (STAFF_ID) ON DELETE RESTRICT,
    INDEX IDX_MED_NAME (MEDICATION_NAME)
);

-- ===== Module 8: Discharge and aftercare =====
CREATE TABLE IF NOT EXISTS DISCHARGE_AFTERCARE_PLAN (
    PLAN_ID                  BIGINT       AUTO_INCREMENT PRIMARY KEY,
    PATIENT_ID               BIGINT       NOT NULL,
    RECOVERY_GOALS           TEXT         NOT NULL,
    AFTERCARE_INSTRUCTIONS   TEXT         NOT NULL,
    DISCHARGE_DATE           DATE,                     -- set when the patient leaves
    FOLLOW_UP_DATE           DATE,
    EMERGENCY_CONTACT_NAME   VARCHAR(100) NOT NULL,    -- who to call on relapse
    EMERGENCY_CONTACT_PHONE  VARCHAR(20)  NOT NULL,
    CREATED_DATE             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PLAN_PATIENT FOREIGN KEY (PATIENT_ID)
        REFERENCES PATIENT (PATIENT_ID) ON DELETE RESTRICT,
    INDEX IDX_PLAN_FOLLOW_UP (FOLLOW_UP_DATE)
);

